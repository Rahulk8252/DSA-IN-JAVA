import java.util.Scanner;
public class numberprint {
    public static void main(Strings[] args){
        Scanner input =new Scanner(System.in);
        System.out.println("enter a number that you want to print");
        int n=input.nextInt();
        int i=1;
        while(i<=n){
            System.out.println(i);
            i++;
        }
    }
    
}
